#!/bin/bash
# СБОРОЧНЫЙ скрипт задачи T03 "Запутанный путь".
#
# Выполняется на этапе сборки в builder-stage.  Готовит файлы в /stage,
# откуда они копируются в финальный образ.  В контейнере этого скрипта нет.
set -euo pipefail

STAGE="${STAGE:-/stage}"
HOME_DIR="$STAGE/home/ctf"

# Генерируем зашифрованный флаг и получаем случайный ключ (hex, 32 символа).
key="$(ctf-make-challenge 'SSL{relative_paths}' "$STAGE")"

# Рабочий каталог студента и соседний каталог с ключом.
mkdir -p "$HOME_DIR/work/logs" "$HOME_DIR/secret"

cat > "$HOME_DIR/secret/key.txt" <<EOF
Ключ расшифровки
================

Достался не тем путём, каким искали.
Ключ (hex, 32 символа):

$key
EOF

cat > "$HOME_DIR/work/current.txt" <<'EOF'
Текущая задача
==============

Ключ лежит в другом каталоге рядом с рабочим.
Подсказка: из этого каталога можно подняться на уровень вверх.
EOF

cat > "$HOME_DIR/work/logs/old.log" <<'EOF'
[2024-01-03 09:00] сервис запущен
[2024-01-03 09:05] плановая проверка завершена
[2024-01-03 18:00] сервис остановлен
EOF

# Права и владельцы.
chown -R ctf:ctf "$HOME_DIR"
chmod -R a+rX "$HOME_DIR"
