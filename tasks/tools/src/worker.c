/*
 * worker -- долгоживущий процесс-пустышка для задач о процессах и
 * переменных окружения (T19, T20 и часть T26).
 *
 * Никакой полезной логики в нём нет: он просто спит вечно, чтобы
 * студент мог изучить его через ps(1), pgrep(1) и /proc.
 *
 * Имя процесса (comm) совпадает с именем файла, поэтому `pgrep -a worker`
 * действительно находит его.
 */
#include <unistd.h>

int main(int argc, char **argv)
{
    (void)argc;
    (void)argv;

    for (;;)
        sleep(3600);

    return 0;
}
