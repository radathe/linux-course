#!/bin/bash
# Запуск фонового сервиса задачи T23 "Подключись к сервису".
#
# Сервер слушает 127.0.0.1:31337 и доступен только внутри контейнера.
# Флаг передаётся через переменную окружения, поэтому в образе и в
# аргументах процесса его нет.
set -euo pipefail

export TASK_FLAG="${TASK_FLAG:-flag{netcat_basics}}"

nohup python3 /opt/server.py >>/var/log/task.log 2>&1 &

# Дать серверу время открыть порт.
sleep 1
