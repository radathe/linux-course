#!/bin/bash
# СБОРОЧНЫЙ скрипт задачи T02 "Скрытая записка".
#
# Выполняется на этапе сборки в builder-stage.  Готовит файлы в /stage,
# откуда они копируются в финальный образ.  В контейнере этого скрипта нет.
set -euo pipefail

STAGE="${STAGE:-/stage}"
HOME_DIR="$STAGE/home/ctf"

# Генерируем зашифрованный флаг и получаем случайный ключ (hex, 32 символа).
key="$(ctf-make-challenge 'SSL{hidden_note}' "$STAGE")"

mkdir -p "$HOME_DIR/Documents" "$HOME_DIR/Downloads"

# Скрытый файл с ключом: обычный `ls` его не показывает.
cat > "$HOME_DIR/Documents/.secret" <<EOF
Скрытая записка
===============

Ключ для расшифровки флага (hex, 32 символа):

$key

Никому не показывать.
EOF

cat > "$HOME_DIR/Documents/report.txt" <<'EOF'
Отчёт за неделю
===============

Всё идёт по плану. Ничего существенного не произошло.
Файлы можно разобрать позже.
EOF

cat > "$HOME_DIR/Documents/todo.txt" <<'EOF'
Список дел
==========

[ ] Разобрать почту
[ ] Обновить документацию
[ ] Проверить резервные копии
EOF

cat > "$HOME_DIR/Downloads/manual.txt" <<'EOF'
Руководство пользователя
========================

Раздел 1. Начало работы.
Раздел 2. Основные команды.
Раздел 3. Частые вопросы.
EOF

cat > "$HOME_DIR/notes.txt" <<'EOF'
Короткие заметки
================

Не всё то золото, что лежит на виду.
Некоторые файлы принято скрывать: их имена начинаются с точки.
EOF

# Права и владельцы.
chown -R ctf:ctf "$HOME_DIR"
chmod -R a+rX "$HOME_DIR"
